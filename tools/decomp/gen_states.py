"""Write src/nomercy/nm_state_ids.h, the enum of wrestler states, from the symbol files.

    py tools/decomp/gen_states.py

Names and numbers come from _re_docs/symbols/nomercy/state_enum.toml, the handler of each state from the
table g_state_handlers (0x80144CF0) and states.toml. Rerun it after renaming a state.
"""
import glob
import os
import re
import struct
import tomllib

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
IMAGE = os.path.join(REPO, "_tools", "ida_nomercy", "nomercy_ovl_e.bin")
TABLE = 0x144CF0


def main():
    with open(os.path.join(REPO, "_re_docs", "symbols", "nomercy", "state_enum.toml"), "rb") as f:
        states = tomllib.load(f)["states"]
    with open(IMAGE, "rb") as f:
        f.seek(TABLE)
        table = struct.unpack(">212I", f.read(4 * 212))
    names = {}
    for path in glob.glob(os.path.join(REPO, "_re_docs", "symbols", "nomercy", "*.toml")):
        with open(path, encoding="utf-8") as f:
            for a, n in re.findall(r'addr = 0x([0-9A-F]+)\r?\nname = "([^"]*)"', f.read()):
                names[int(a, 16)] = n
    seen = set()
    lines = [
        "// Generated by tools/decomp/gen_states.py from _re_docs/symbols/nomercy/state_enum.toml. Do not edit.",
        "// The wrestler states: each is the index of its handler in g_state_handlers (0x80144CF0).",
        "#pragma once",
        "",
        "namespace nm {",
        "namespace state {",
        "",
        "enum Id : s32 {",
    ]
    for key, name in sorted(states.items(), key=lambda kv: int(kv[0], 16)):
        n = int(key, 16)
        if name in seen:
            raise SystemExit("duplicate state name: " + name)
        seen.add(name)
        handler = names.get(table[n], "")
        lines.append("    %s = 0x%02X,  // %s" % (name, n, handler))
    lines += ["};", "", "}  // namespace state", "}  // namespace nm", ""]
    out = os.path.join(REPO, "src", "nomercy", "nm_state_ids.h")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print("wrote %d states to %s" % (len(seen), out))


if __name__ == "__main__":
    main()
