"""Write the enums of wrestler states and CPU AI modes from the symbol files.

    py tools/decomp/gen_states.py

src/nomercy/nm_state_ids.h comes from _re_docs/symbols/nomercy/state_enum.toml and nm_ai_mode_ids.h from
ai_mode_enum.toml: the names and each entry's doc comment (its [notes], which editors show on hover). The function of
each comes from the tables g_state_handlers (0x80144CF0) and g_ai_modes (0x80145A10) and the symbol files. Rerun it
after renaming an entry or changing a note.
"""
import glob
import os
import re
import struct
import tomllib

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
IMAGE = os.path.join(REPO, "_tools", "ida_nomercy", "nomercy_ovl_e.bin")
SYMBOLS = os.path.join(REPO, "_re_docs", "symbols", "nomercy")


def symbol_names():
    names = {}
    for path in glob.glob(os.path.join(SYMBOLS, "*.toml")):
        with open(path, encoding="utf-8") as f:
            for a, n in re.findall(r'addr = 0x([0-9A-F]+)\r?\nname = "([^"]*)"', f.read()):
                names[int(a, 16)] = n
    return names


def write_enum(toml_name, section, table_addr, count, header, namespace, intro, value_format, unrecorded_note):
    with open(os.path.join(SYMBOLS, toml_name), "rb") as f:
        data = tomllib.load(f)
    entries = data[section]
    notes = data.get("notes", {})
    recorded = set(data.get("recorded", {}).get("modes", []))
    for key in notes:
        if key not in entries:
            raise SystemExit("%s: note for an entry with no name: %s" % (toml_name, key))
    with open(IMAGE, "rb") as f:
        f.seek(table_addr - 0x80000000)
        table = struct.unpack(">%dI" % count, f.read(4 * count))
    names = symbol_names()
    seen = set()
    lines = [
        "// Generated by tools/decomp/gen_states.py from _re_docs/symbols/nomercy/%s. Do not edit." % toml_name,
        "// " + intro,
        "#pragma once",
        "",
        "namespace nm {",
        "namespace %s {" % namespace,
        "",
        "enum Id : s32 {",
    ]
    for key, name in sorted(entries.items(), key=lambda kv: int(kv[0], 0)):
        n = int(key, 0)
        if name in seen:
            raise SystemExit("%s: duplicate name: %s" % (toml_name, name))
        seen.add(name)
        text = (value_format % n) + ", " + names.get(table[n], "") + "."
        if notes.get(key):
            text += " " + notes[key]
        if unrecorded_note and n not in recorded:
            text += " " + unrecorded_note
        lines.append("    /// " + text)
        lines.append("    %s = %s," % (name, value_format % n))
    lines += ["};", "", "}  // namespace %s" % namespace, "}  // namespace nm", ""]
    out = os.path.join(REPO, "src", "nomercy", header)
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print("wrote %d entries to %s" % (len(seen), out))


def main():
    write_enum("state_enum.toml", "states", 0x80144CF0, 212, "nm_state_ids.h", "state",
               "The wrestler states: each is the index of its handler in g_state_handlers (0x80144CF0).", "0x%02X", None)
    write_enum("ai_mode_enum.toml", "modes", 0x80145A10, 145, "nm_ai_mode_ids.h", "ai_mode",
               "The CPU's AI modes: each is the index of its function in g_ai_modes (0x80145A10).", "%d",
               "Not yet seen in a recording: named from the code.")


if __name__ == "__main__":
    main()
