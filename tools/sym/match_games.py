"""Match functions between two games by their machine code, to carry names across.

    py tools/sym/match_games.py [--src wcw] [--dst revenge] [--out FILE.toml]

Each function's MIPS code (from the flat images the IDA builds lay out, _tools/ida_<game>/*.bin,
with sizes from export.json) is normalised so that only what moves between builds is hidden:
jal targets, lui immediates, and the low halves (%lo) of addresses built from a lui (tracked per
register through the function). Struct offsets, constants and control flow stay. Functions with
identical normalised code that is unique in both games are matched; then ambiguous ones are
resolved through matched callers / callees. Prints statistics and writes the documented matches
as [[func]] entries for the destination's symbol files.
"""
import argparse
import glob
import hashlib
import json
import os
import struct
import sys
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
import symdb  # noqa: E402

BASE = 0x80000000
LOADSTORE = {0x08, 0x09, 0x20, 0x21, 0x23, 0x24, 0x25, 0x27, 0x28, 0x29, 0x2B, 0x31, 0x35, 0x39, 0x3D, 0x37, 0x3F}


def load(game):
    d = os.path.join(REPO, "_tools", "ida_" + game)
    with open(os.path.join(d, "export.json"), encoding="utf-8") as f:
        ex = json.load(f)
    image = open(glob.glob(os.path.join(d, "*.bin"))[0], "rb").read()
    return {fn["addr"]: fn for fn in ex["funcs"]}, image


def shape(image, addr, size):
    out = []
    hi = set()  # registers holding a lui'd upper half
    for ea in range(addr, addr + size, 4):
        w = struct.unpack_from(">I", image, ea - BASE)[0]
        op = w >> 26
        rs, rt = (w >> 21) & 31, (w >> 16) & 31
        if op == 0x03 or op == 0x02:          # jal / j
            w &= 0xFC000000
        elif op == 0x0F:                      # lui
            w &= 0xFFFF0000
            hi.add(rt)
        elif (op in LOADSTORE or op == 0x09) and rs in hi:
            w &= 0xFFFF0000
            if op == 0x09 or op in (0x23, 0x20, 0x21, 0x24, 0x25, 0x37):
                hi.discard(rt) if rt != rs else None
        elif op == 0 and (w & 0x3F) in (0x21, 0x2D) and rs in hi:   # addu base, hi, idx
            hi.add((w >> 11) & 31)
        out.append(w)
    return hashlib.sha1(struct.pack(">%dI" % len(out), *out)).hexdigest()


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--src", default="wcw")
    ap.add_argument("--dst", default="revenge")
    ap.add_argument("--out")
    args = ap.parse_args()

    src, simg = load(args.src)
    dst, dimg = load(args.dst)
    hs = {a: shape(simg, a, fn["size"]) for a, fn in src.items() if fn["size"] >= 16}
    hd = {a: shape(dimg, a, fn["size"]) for a, fn in dst.items() if fn["size"] >= 16}
    by_s, by_d = defaultdict(list), defaultdict(list)
    for a, h in hs.items():
        by_s[h].append(a)
    for a, h in hd.items():
        by_d[h].append(a)

    match = {}
    for h, sa in by_s.items():
        da = by_d.get(h)
        if da and len(sa) == 1 and len(da) == 1:
            match[sa[0]] = da[0]
    print("unique exact matches:", len(match))

    changed = True
    while changed:
        changed = False
        used = set(match.values())
        for h, sa in by_s.items():
            free = [d for d in by_d.get(h, []) if d not in used]
            for s in sa:
                if s in match or not free:
                    continue
                nbr = {match[x] for x in src[s]["callers"] + src[s]["callees"] if x in match}
                cands = [d for d in free if nbr & set(dst[d]["callers"] + dst[d]["callees"])]
                if len(cands) == 1:
                    match[s] = cands[0]
                    used.add(cands[0])
                    free.remove(cands[0])
                    changed = True
    print("after neighbour propagation:", len(match))

    documented = {f["addr"]: f for f in symdb.Symbols(args.src).funcs}
    have = {f["addr"] for f in symdb.Symbols(args.dst).funcs}
    m_doc = [s for s in match if s in documented]
    print("documented %s functions matched: %d of %d" % (args.src, len(m_doc), len(documented)))
    ovl = [s for s in m_doc if s >= 0x80090000]
    print("  of which in the match overlay: %d" % len(ovl))
    if args.out:
        hits = [(s, match[s]) for s in sorted(m_doc) if match[s] not in have]
        with open(args.out, "w", encoding="utf-8") as f:
            f.write("# Generated by tools/sym/match_games.py: identical normalised machine code in %s.\n" % args.src)
            for s, d in hits:
                e = documented[s]
                f.write('\n[[func]]\naddr = 0x%08X\nname = "%s"\n' % (d, e["name"]))
                if e.get("proto"):
                    f.write('proto = "%s"\n' % e["proto"].replace('"', "'"))
                desc = (e.get("desc") or "").replace('"', "'").replace("\\", "/")
                f.write('desc = "%s (same code as %s 0x%08X)."\nstatus = "likely"\n' % (desc.rstrip("."), args.src, s))
        print("wrote", len(hits), "entries to", args.out)


if __name__ == "__main__":
    main()
